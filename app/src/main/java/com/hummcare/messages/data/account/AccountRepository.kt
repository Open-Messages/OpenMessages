package com.hummcare.messages.data.account

import android.app.Activity
import android.content.Context
import androidx.credentials.ClearCredentialStateRequest
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.firebase.FirebaseApp
import com.google.firebase.auth.FirebaseAuth
import com.google.firebase.auth.FirebaseUser
import com.google.firebase.auth.GoogleAuthProvider
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asStateFlow
import kotlinx.coroutines.tasks.await

data class Account(val uid: String, val email: String?, val displayName: String?)

/**
 * Optional Google sign-in backed by Firebase Auth. The app works fully without an account; it's
 * only needed for OTP sync. When the build has no google-services.json, [isAvailable] is false
 * and every call is a no-op.
 */
class AccountRepository(private val context: Context, firebaseApp: FirebaseApp?) {
    private val auth: FirebaseAuth? = firebaseApp?.let(FirebaseAuth::getInstance)
    private val state = MutableStateFlow(auth?.currentUser?.toAccount())

    val isAvailable: Boolean get() = auth != null && webClientId() != null
    val account: StateFlow<Account?> = state.asStateFlow()
    val current: Account? get() = state.value

    init {
        auth?.addAuthStateListener { state.value = it.currentUser?.toAccount() }
    }

    /**
     * Shows the "Sign in with Google" sheet and signs in to Firebase with the chosen account. Returns
     * null if the user dismissed the sheet; throws on any other failure.
     */
    suspend fun signInWithGoogle(activity: Activity): Account? {
        val auth = auth ?: error("Firebase isn't configured in this build")
        val clientId = webClientId() ?: error("Missing default_web_client_id; check google-services.json")
        val request = GetCredentialRequest.Builder()
            .addCredentialOption(GetSignInWithGoogleOption.Builder(clientId).build())
            .build()
        val credential = try {
            CredentialManager.create(activity).getCredential(activity, request).credential
        } catch (_: GetCredentialCancellationException) {
            return null
        }
        check(credential is CustomCredential && credential.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
            "Unexpected credential type ${credential.type}"
        }
        val idToken = GoogleIdTokenCredential.createFrom(credential.data).idToken
        val user = auth.signInWithCredential(GoogleAuthProvider.getCredential(idToken, null)).await().user
        return user?.toAccount()?.also { state.value = it }
    }

    suspend fun signOut() {
        auth?.signOut()
        state.value = null
        // Forget the chosen Google account so the next sign-in shows the account picker again.
        runCatching { CredentialManager.create(context).clearCredentialState(ClearCredentialStateRequest()) }
    }

    /** OAuth web client ID generated by the google-services plugin; looked up by name so builds without it compile. */
    private fun webClientId(): String? {
        val id = context.resources.getIdentifier("default_web_client_id", "string", context.packageName)
        return if (id == 0) null else context.getString(id).takeIf { it.isNotBlank() }
    }

    private fun FirebaseUser.toAccount() = Account(uid = uid, email = email, displayName = displayName)
}
